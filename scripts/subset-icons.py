#!/usr/bin/env python3
"""Build a tiny Tabler Icons webfont containing only the icons the app uses.

The full @tabler/icons-webfont is ~750 KB (woff2) + 214 KB CSS. This keeps
just the glyphs referenced in src/ and writes:
  src/vendor/tabler-icons.css
  src/vendor/tabler-icons.woff2

Run after using a new icon:  python3 scripts/subset-icons.py
Needs: pip install fonttools brotli
"""
import pathlib, re
from fontTools import subset

ROOT = pathlib.Path(__file__).resolve().parent.parent
PKG = ROOT / "node_modules/@tabler/icons-webfont"
OUT = ROOT / "src/vendor"

# Icons built from template strings (ti-${...}) that a plain scan can't see.
DYNAMIC = {"chevron-up", "chevron-down", "camera", "camera-plus", "eye", "eye-off",
           "loader-2", "flame", "leaf", "lock-open", "file-type-xls", "alert-triangle", "pencil",
           "circle", "calendar", "progress", "circle-check", "list-check"}

src = "\n".join(p.read_text() for p in (ROOT / "src").rglob("*.jsx"))
used = set(re.findall(r"ti-([a-z0-9-]+)", src)) | DYNAMIC
used = {u for u in used if not u.endswith("-")}

css = (PKG / "tabler-icons.css").read_text()
rules = dict(re.findall(r'\.ti-([a-z0-9-]+):before\s*\{\s*content:\s*"\\([0-9a-f]+)";?\s*\}', css))
missing = sorted(u for u in used if u not in rules)
if missing:
    raise SystemExit(f"Unknown Tabler icons: {missing}")

codepoints = sorted(int(rules[u], 16) for u in used)
OUT.mkdir(parents=True, exist_ok=True)
opts = subset.Options(); opts.flavor = "woff2"; opts.layout_features = []
font = subset.load_font(str(PKG / "fonts/tabler-icons.woff2"), opts)
sub = subset.Subsetter(opts); sub.populate(unicodes=codepoints); sub.subset(font)
subset.save_font(font, str(OUT / "tabler-icons.woff2"), opts)

lines = [
    "/* Generated by scripts/subset-icons.py — Tabler Icons (MIT) subset. Do not edit. */",
    '@font-face{font-family:"tabler-icons";font-style:normal;font-weight:400;font-display:block;'
    'src:url("./tabler-icons.woff2") format("woff2")}',
    '.ti{font-family:"tabler-icons"!important;speak:none;font-style:normal;font-weight:normal;'
    'font-variant:normal;text-transform:none;line-height:1;-webkit-font-smoothing:antialiased;'
    '-moz-osx-font-smoothing:grayscale}',
]
lines += [f'.ti-{u}:before{{content:"\\{rules[u]}"}}' for u in sorted(used)]
(OUT / "tabler-icons.css").write_text("\n".join(lines) + "\n")
print(f"{len(used)} icons → {(OUT / 'tabler-icons.woff2').stat().st_size} bytes")
